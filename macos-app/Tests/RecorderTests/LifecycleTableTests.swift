import XCTest
@testable import Recorder

@MainActor
final class LifecycleTableTests: XCTestCase {
    private func newRun(oneShot: Bool = false) -> Run {
        Run(oneShot: oneShot, stopAt: nil) { _, _ in }
    }

    func testARunGoesFromStartThroughItsAttemptsToRest() {
        var life = RecorderLifecycle()
        let r = newRun()
        XCTAssertEqual(life.state, .stopped)
        XCTAssertEqual(life.take(.start(r)), .moved)
        XCTAssertEqual(life.state, .starting)
        XCTAssertEqual(life.message, RecorderLifecycle.openingMessage)
        XCTAssertTrue(life.running)
        XCTAssertFalse(life.stopping)
        XCTAssertFalse(life.capturing)
        XCTAssertEqual(life.take(.opened(r)), .moved)
        life.take(.stated(r))
        XCTAssertEqual(life.state, .recording)
        XCTAssertNil(life.message)
        XCTAssertTrue(life.capturing)
        life.take(.attempt(.waiting))
        XCTAssertEqual(life.state, .waiting)
        XCTAssertFalse(life.capturing, "a closed gate or idle input takes no frame")
        life.take(.attempt(.recovering))
        XCTAssertEqual(life.state, .recovering)
        XCTAssertEqual(life.message, RecorderLifecycle.recoveringMessage)
        XCTAssertTrue(life.capturing)
        XCTAssertEqual(life.take(.ended(r, .stopped)), .moved)
        XCTAssertEqual(life.state, .stopped, "a run that ended takes no more frames from now")
        XCTAssertTrue(life.running)
        XCTAssertTrue(life.stopping)
        XCTAssertFalse(life.records(r))
        XCTAssertTrue(life.admits(r), "its waiting frames still publish")
        XCTAssertEqual(life.take(.attempt(.recording)), .unchanged, "a frame published while closing moves nothing")
        XCTAssertEqual(life.take(.released(r)), .moved)
        XCTAssertFalse(life.running)
        XCTAssertFalse(life.stopping)
        XCTAssertNil(life.run)
    }

    func testAStopRefusesAStartUntilTheRunIsReleasedAndIgnoresTheRunsLateEvents() {
        var life = RecorderLifecycle()
        let first = newRun(), second = newRun()
        life.take(.start(first))
        XCTAssertEqual(life.take(.start(second)), .unchanged, "a second start only replaces the timer")
        XCTAssertTrue(life.run === first)
        XCTAssertEqual(life.take(.oneShot(second)), .refused(.alreadyActive))
        XCTAssertEqual(life.take(.refusedWithoutGrant), .refused(.alreadyActive))
        XCTAssertEqual(life.take(.stop), .moved)
        XCTAssertEqual(life.state, .stopped)
        XCTAssertFalse(life.admits(first), "a stopped run publishes no frame")
        XCTAssertEqual(life.take(.start(second)), .refused(.stillPausing))
        XCTAssertEqual(life.take(.stop), .unchanged, "a second stop joins the first")
        XCTAssertEqual(life.take(.opened(first)), .unchanged, "storage that opens after the stop")
        XCTAssertEqual(life.take(.ended(first, .captured)), .unchanged)
        XCTAssertEqual(life.take(.storageLost(first)), .unchanged, "a failure after a stop is its cancellation")
        XCTAssertEqual(life.take(.openingFailed(first)), .unchanged)
        XCTAssertEqual(life.take(.released(first)), .moved)
        XCTAssertEqual(life.state, .stopped)
        XCTAssertEqual(life.take(.start(second)), .moved)
    }

    func testEventsOfAnotherRunChangeNothing() {
        var life = RecorderLifecycle()
        let current = newRun(), stale = newRun()
        life.take(.start(current))
        life.take(.opened(current))
        life.take(.stated(current))
        XCTAssertEqual(life.take(.opened(stale)), .unchanged)
        XCTAssertEqual(life.take(.storageLost(stale)), .unchanged)
        XCTAssertEqual(life.take(.openingFailed(stale)), .unchanged)
        XCTAssertEqual(life.take(.ended(stale, .stopped)), .unchanged)
        XCTAssertEqual(life.take(.stated(stale)), .unchanged)
        XCTAssertEqual(life.take(.released(stale)), .unchanged)
        XCTAssertFalse(life.admits(stale))
        XCTAssertFalse(life.records(stale))
        XCTAssertEqual(life.state, .recording)
    }

    func testTheScreenGrantLostAndGivenBack() {
        var life = RecorderLifecycle()
        let r = newRun()
        life.take(.start(r))
        XCTAssertEqual(life.take(.screenAllowed), .unchanged, "no attempt yet while opening")
        life.take(.opened(r))
        life.take(.stated(r))
        XCTAssertEqual(life.take(.screenAllowed), .unchanged, "every attempt with the grant says so")
        life.take(.attempt(.waiting))
        XCTAssertEqual(life.take(.screenAllowed), .unchanged, "the grant alone does not end a wait")
        XCTAssertEqual(life.state, .waiting)
        life.take(.attempt(.permissionRequired))
        XCTAssertEqual(life.state, .permissionRequired)
        XCTAssertEqual(life.message, Recorder.screenRecordingMessage)
        XCTAssertTrue(life.running, "a lost grant does not stop the run")
        XCTAssertFalse(life.capturing)
        XCTAssertEqual(life.take(.attempt(.recovering)), .unchanged,
                       "a frame of an earlier attempt, published late, does not say the grant is back")
        XCTAssertEqual(life.state, .permissionRequired)
        XCTAssertFalse(life.capturing)
        XCTAssertEqual(life.take(.screenAllowed), .moved)
        XCTAssertEqual(life.state, .recording)
    }

    func testALostStoreMovesRecordingToRecoveringAndOnlyAStopEndsTheRun() {
        var life = RecorderLifecycle()
        let r = newRun()
        life.take(.start(r))
        life.take(.opened(r))
        life.take(.stated(r))
        life.take(.attempt(.permissionRequired))
        XCTAssertEqual(life.take(.storageLost(r)), .moved)
        XCTAssertEqual(life.state, .recovering, "whatever the last attempt showed")
        XCTAssertEqual(life.message, RecorderLifecycle.recoveringMessage)
        XCTAssertTrue(life.running)
        XCTAssertFalse(life.stopping)
        XCTAssertTrue(life.capturing, "trying to take frames")
        XCTAssertTrue(life.records(r), "the run goes on toward its next opening")
        XCTAssertTrue(life.admits(r))
        XCTAssertEqual(life.take(.storageLost(r)), .moved, "a reopened tenure lost again stays recovering")
        XCTAssertEqual(life.state, .recovering)
        XCTAssertEqual(life.take(.attempt(.recording)), .moved, "a saved frame ends it")
        XCTAssertEqual(life.state, .recording)
        XCTAssertEqual(life.take(.ended(r, .stopped)), .moved, "the run's timer")
        XCTAssertEqual(life.take(.storageLost(r)), .unchanged, "a closing run ends as it was ending")
        XCTAssertEqual(life.state, .stopped)
        XCTAssertTrue(life.admits(r), "its waiting frames still publish")
        life.take(.released(r))
        XCTAssertEqual(life.state, .stopped)
        XCTAssertNil(life.message)
    }

    func testAnOpeningThatFailsRetriesShowingRecoveringAndStartsNothing() {
        var life = RecorderLifecycle()
        let r = newRun()
        life.take(.start(r))
        XCTAssertEqual(life.take(.openingFailed(r)), .moved)
        XCTAssertEqual(life.state, .recovering, "not starting: the opening failed and is tried again")
        XCTAssertEqual(life.message, RecorderLifecycle.recoveringMessage)
        XCTAssertTrue(life.running)
        XCTAssertFalse(life.stopping)
        XCTAssertTrue(life.records(r))
        XCTAssertTrue(life.settle(off: []) == ([], []), "nothing starts before the opening is stated")
        life.take(.opened(r))
        XCTAssertEqual(life.take(.openingFailed(r)), .moved, "runtime.json did not take the opening")
        XCTAssertEqual(life.state, .recovering)
        XCTAssertTrue(life.settle(off: []) == ([], []))
        life.take(.opened(r))
        life.take(.stated(r))
        XCTAssertEqual(life.state, .recording)
        XCTAssertTrue(life.settle(off: []) == ([], [.machine, .input, .audio]))
        XCTAssertEqual(life.take(.stop), .moved)
        life.take(.released(r))
        XCTAssertEqual(life.state, .stopped)
    }

    func testAOneShotWhoseStoreIsLostRestsStopped() {
        var life = RecorderLifecycle()
        let shot = newRun(oneShot: true)
        life.take(.oneShot(shot))
        life.take(.opened(shot))
        life.take(.stated(shot))
        XCTAssertEqual(life.take(.storageLost(shot)), .moved)
        XCTAssertEqual(life.state, .stopped, "a one-shot does not recover")
        XCTAssertTrue(life.stopping)
        life.take(.released(shot))
        XCTAssertEqual(life.state, .stopped)
        let unopened = newRun(oneShot: true)
        life.take(.oneShot(unopened))
        XCTAssertEqual(life.take(.openingFailed(unopened)), .moved)
        XCTAssertEqual(life.state, .stopped, "nor does its opening retry")
        life.take(.released(unopened))
        XCTAssertEqual(life.state, .stopped)
    }

    func testAStopWhileTheRunEndsOnItsOwnDropsItsWaitingFrames() {
        var life = RecorderLifecycle()
        let r = newRun()
        life.take(.start(r))
        life.take(.opened(r))
        life.take(.stated(r))
        life.take(.ended(r, .stopped))
        XCTAssertEqual(life.take(.stop), .moved)
        XCTAssertFalse(life.admits(r))
    }

    func testAOneShotRestsInItsOutcomeAndRefusesAStart() {
        var life = RecorderLifecycle()
        let shot = newRun(oneShot: true)
        XCTAssertEqual(life.take(.oneShot(shot)), .moved)
        XCTAssertEqual(life.take(.start(newRun())), .refused(.alreadyActive), "a one-shot has no timer to replace")
        life.take(.opened(shot))
        life.take(.stated(shot))
        life.take(.ended(shot, .captured))
        XCTAssertEqual(life.state, .captured, "the cleanup's write says what the release reaches")
        XCTAssertEqual(life.take(.ended(shot, .stopped)), .unchanged, "the cleanup's own end comes after")
        life.take(.released(shot))
        XCTAssertEqual(life.state, .captured)
        let gap = newRun(oneShot: true)
        life.take(.oneShot(gap))
        life.take(.opened(gap))
        life.take(.stated(gap))
        life.take(.ended(gap, .gap))
        life.take(.released(gap))
        XCTAssertEqual(life.state, .gap)
    }

    func testAOneShotWithoutTheGrantRestsAtOnce() {
        var life = RecorderLifecycle()
        XCTAssertEqual(life.take(.refusedWithoutGrant), .moved)
        XCTAssertEqual(life.state, .permissionRequired)
        XCTAssertEqual(life.message, Recorder.screenRecordingMessage)
        XCTAssertFalse(life.running)
    }

    func testProducersStartOnceOpenFollowOffAndStopAfterTheSealAudioFirst() {
        var life = RecorderLifecycle()
        let r = newRun()
        life.take(.start(r))
        XCTAssertTrue(life.settle(off: []) == ([], []), "nothing starts before the store opens")
        life.take(.opened(r))
        XCTAssertEqual(life.state, .recording, "the opening's write states the store open")
        XCTAssertTrue(life.settle(off: []) == ([], []), "nothing starts before runtime.json took it")
        XCTAssertTrue(life.records(r))
        life.take(.stated(r))
        XCTAssertTrue(life.settle(off: [.audio]) == ([], [.machine, .input]))
        XCTAssertTrue(life.settle(off: [.input]) == ([.input], [.audio]), "stops first, then starts")
        XCTAssertTrue(life.settle(off: [.input, .screen]) == ([], []), "screen is a gate, never started")
        life.take(.stop)
        XCTAssertTrue(life.settle(off: []) == ([], []), "a change while closing waits for the seal")
        XCTAssertEqual(life.started, [.machine, .audio])
        XCTAssertTrue(life.settle(off: [], seal: true) == ([.audio, .machine], []))
        XCTAssertEqual(life.started, [])
        XCTAssertTrue(life.settle(off: []) == ([], []), "nothing starts again after the seal")
    }
}
